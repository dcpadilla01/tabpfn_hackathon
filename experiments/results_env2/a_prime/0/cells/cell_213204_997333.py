e1 = agent_api.load_saved('e001_rfm.parquet')
e2 = agent_api.load_saved('e002_composition.parquet')
print('e1', e1.shape)
print('e2', e2.shape)
print('E1 cols:', sorted(map(str, e1.columns)))
print('E2 cols:', sorted(map(str, e2.columns)))
key = ['household_key','snapshot_day']
common = [c for c in e1.columns if c in e2.columns and c not in key]
print('common cols:', common)
m = e1.merge(e2, on=key, how='inner', suffixes=('', '_DUP'))
m = m.drop(columns=[c+'_DUP' for c in common])
print('merged', m.shape)
p = agent_api.save_table(m, 'e003_union.parquet')
print('saved', p)
tt = agent_api.train_targets()
print('target mean/std/zero-share:', round(tt.future_spend_4w.mean(),2), round(tt.future_spend_4w.std(),2), round((tt.future_spend_4w==0).mean(),3))
mm = m.merge(tt, on=key, how='inner')
num = pd.concat([mm.select_dtypes(include=[np.number]), mm.select_dtypes(include=['bool']).astype(float)], axis=1)
cor = num.corr()['future_spend_4w'].drop(['future_spend_4w','snapshot_day'], errors='ignore')
cor = cor.reindex(cor.abs().sort_values(ascending=False).index)
print('--- top correlations ---')
print(cor.head(35).round(3))
print('--- weakest ---')
print(cor.tail(8).round(3))

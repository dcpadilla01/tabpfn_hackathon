import agent_api as api, pandas as pd, numpy as np
base = api.load_saved('e012_dorm.parquet')
print('base shape', base.shape)
print(list(base.columns))
t = api.train_targets()
m = base.merge(t, on=['household_key','snapshot_day'])
print('merged', m.shape)
print(m['future_spend_4w'].describe())
num = m.select_dtypes('number')
c = num.corr()['future_spend_4w'].drop('future_spend_4w')
print('\nTop |corr| with target:')
print(c.abs().sort_values(ascending=False).head(25))
print('\nMost negative corr:')
print(c.sort_values().head(10))
